def set_scenario_rate_card(
    scenario_id: int,
    rate_card_id: Optional[int],
    quartile: str = "p50",
) -> Dict[str, Any]:
    q = (quartile or "p50").lower()
    if q not in ("p25", "p50", "p75"):
        q = "p50"
    now = datetime.utcnow().isoformat()
    with _connect() as conn:
        scenario = conn.execute(
            "SELECT * FROM scenarios WHERE id = ?", (scenario_id,)
        ).fetchone()
        if not scenario:
            raise ValueError(f"Scenario {scenario_id} not found")
        if rate_card_id is not None:
            rc = conn.execute(
                "SELECT dataset_id FROM rate_card_definitions WHERE id = ?",
                (rate_card_id,),
            ).fetchone()
            if not rc or rc["dataset_id"] != scenario["dataset_id"]:
                raise ValueError("Rate card does not belong to this dataset")
        conn.execute(
            """
            UPDATE scenarios
            SET rate_card_id = ?, rate_card_quartile = ?, updated_at = ?
            WHERE id = ?
            """,
            (rate_card_id, q, now, scenario_id),
        )
        conn.commit()
    updated = get_scenario(scenario_id)
    return updated or {}


def lookup_rate_card_cost(
    scenario_id: int,
    values: Dict[str, Any],
) -> Optional[Dict[str, Any]]:
    from services.rate_card_service import (
        build_composite_key,
        lookup_cost_from_row,
        parse_property_cols,
        quartile_value,
    )

    scenario = get_scenario(scenario_id)
    if not scenario or not scenario.get("rate_card_id"):
        return None
    rate_card = get_rate_card(int(scenario["rate_card_id"]))
    if not rate_card:
        return None

    property_cols = rate_card.get("property_cols") or []
    composite_key = build_composite_key(values, property_cols)
    row = next((r for r in rate_card.get("rows", []) if r["composite_key"] == composite_key), None)
    quartile = scenario.get("rate_card_quartile") or "p50"
    cost = lookup_cost_from_row(row, quartile)
    return {
        "composite_key": composite_key,
        "cost": cost,
        "quartile": quartile,
        "is_available": bool(row and (row.get("is_available") or row.get("is_manual_override"))),
        "is_manual_override": bool(row.get("is_manual_override")) if row else False,
        "sample_count": row.get("sample_count") if row else 0,
    }

