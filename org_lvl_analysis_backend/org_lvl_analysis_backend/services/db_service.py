def clone_employee(
    scenario_id: int,
    source_emp_id: str,
    new_emp_id: str,
    new_mgr_id: Optional[str] = None,
    username: str = "",
) -> Dict[str, Any]:
    """Clone an existing position into a new scenario record (is_added=1)."""
    now = datetime.utcnow().isoformat()
    with _connect() as conn:
        c = conn.cursor()
        row = c.execute(
            """
            SELECT mgr_id, level, fte, flc, data_json
            FROM scenario_records WHERE scenario_id = ? AND emp_id = ?
            """,
            (scenario_id, source_emp_id),
        ).fetchone()
        if not row:
            raise ValueError(f"Employee {source_emp_id} not found in scenario {scenario_id}")

        dup = c.execute(
            "SELECT id FROM scenario_records WHERE scenario_id = ? AND emp_id = ?",
            (scenario_id, new_emp_id),
        ).fetchone()
        if dup:
            raise ValueError(f"Employee ID {new_emp_id} already exists in this scenario")

        data = json.loads(row["data_json"])
        mgr_id = new_mgr_id if new_mgr_id is not None else row["mgr_id"]
        level = row["level"]
        fte = row["fte"]
        flc = row["flc"]

        scenario = c.execute(
            "SELECT dataset_id FROM scenarios WHERE id = ?", (scenario_id,)
        ).fetchone()
        dataset = c.execute(
            "SELECT emp_col, mgr_col FROM datasets WHERE id = ?",
            (scenario["dataset_id"],),
        ).fetchone()
        if dataset:
            if dataset["emp_col"]:
                data[dataset["emp_col"]] = new_emp_id
            if dataset["mgr_col"]:
                data[dataset["mgr_col"]] = mgr_id

        c.execute(
            """
            INSERT INTO scenario_records
                (scenario_id, emp_id, mgr_id, level, fte, flc,
                 is_flagged_removed, is_added, data_json)
            VALUES (?, ?, ?, ?, ?, ?, 0, 1, ?)
            """,
            (scenario_id, new_emp_id, mgr_id, level, fte, flc, json.dumps(data, default=str)),
        )
        c.execute(
            """
            INSERT INTO change_log
                (scenario_id, action, emp_id, field, old_value, new_mgr_id, timestamp, username)
            VALUES (?, 'clone', ?, 'source_emp_id', ?, ?, ?, ?)
            """,
            (scenario_id, new_emp_id, source_emp_id, mgr_id, now, username),
        )
        c.execute("UPDATE scenarios SET updated_at = ? WHERE id = ?", (now, scenario_id))
        conn.commit()

        data["__emp_id"] = new_emp_id
        data["__mgr_id"] = mgr_id
        data["Level"] = level
        data["is_added"] = True
        data["is_flagged_removed"] = False
        return data


def flag_employee(
    scenario_id: int,
    emp_id: str,
    flagged: bool,
    username: str = "",
) -> Dict[str, Any]:
    """Flag/unflag an employee and cascade to all descendants."""
    now = datetime.utcnow().isoformat()
    with _connect() as conn:
        c = conn.cursor()
        root_row = c.execute(
            "SELECT mgr_id, data_json FROM scenario_records WHERE scenario_id = ? AND emp_id = ?",
            (scenario_id, emp_id),
        ).fetchone()
        if not root_row:
            raise ValueError(f"Employee {emp_id} not found in scenario {scenario_id}")

        subtree_rows = c.execute(
            """
            WITH RECURSIVE subtree AS (
                SELECT emp_id FROM scenario_records
                WHERE scenario_id = ? AND emp_id = ?
              UNION ALL
                SELECT sr.emp_id FROM scenario_records sr
                JOIN subtree st ON sr.mgr_id = st.emp_id
                WHERE sr.scenario_id = ?
            )
            SELECT emp_id FROM subtree
            """,
            (scenario_id, emp_id, scenario_id),
        ).fetchall()

        affected_ids = [r["emp_id"] for r in subtree_rows]
        placeholders = ",".join("?" * len(affected_ids))
        c.execute(
            f"UPDATE scenario_records SET is_flagged_removed = ? "
            f"WHERE scenario_id = ? AND emp_id IN ({placeholders})",
            [1 if flagged else 0, scenario_id] + affected_ids,
        )
        c.execute(
            """
            INSERT INTO change_log
                (scenario_id, action, emp_id, timestamp, username)
            VALUES (?, ?, ?, ?, ?)
            """,
            (scenario_id, "flag_remove" if flagged else "unflag_restore", emp_id, now, username),
        )
        c.execute("UPDATE scenarios SET updated_at = ? WHERE id = ?", (now, scenario_id))
        conn.commit()

        data = json.loads(root_row["data_json"])
        data["__emp_id"] = emp_id
        data["__mgr_id"] = root_row["mgr_id"]
        data["is_flagged_removed"] = flagged
        return data


