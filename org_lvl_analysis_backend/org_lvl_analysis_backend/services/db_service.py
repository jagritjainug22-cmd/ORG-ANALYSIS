# Helpers
# ---------------------------------------------------------------------------

def _to_str(v: Any) -> Optional[str]:
    if v is None:
        return None
    s = str(v)
    if s.lower() in ("nan", "none", ""):
        return None
    return s


def _to_int(v: Any) -> Optional[int]:
    try:
        if v is None or v == "":
            return None
        return int(float(v))
    except (TypeError, ValueError):
        return None


def _to_float(v: Any) -> Optional[float]:
    try:
        if v is None or v == "":
            return None
        f = float(v)
        if f != f:  # NaN
            return None
        return f
    except (TypeError, ValueError):
        return None

