def get_rate_card(rate_card_id: int) -> Optional[Dict[str, Any]]:
    from services.rate_card_service import parse_property_cols

    with _connect_ro() as conn:
        row = conn.execute(
            "SELECT * FROM rate_card_definitions WHERE id = ?", (rate_card_id,)
        ).fetchone()
        if not row:
            return None
        definition = dict(row)
        definition["property_cols"] = parse_property_cols(definition.get("property_cols_json"))
        definition["rows"] = [
            dict(r)
            for r in conn.execute(
                "SELECT * FROM rate_card_rows WHERE rate_card_id = ? ORDER BY composite_key",
                (rate_card_id,),
            ).fetchall()
        ]
        for r in definition["rows"]:
            r["is_manual_override"] = bool(r.get("is_manual_override"))
            r["is_available"] = r.get("p50") is not None or r.get("avg_cost") is not None
        return definition


